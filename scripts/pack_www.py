#!/usr/bin/env python3
"""Pack build/temp/www/ → build/temp/www.pak (FLWW) + src/net/www_bundle_meta.h

Format (little-endian):
  magic[4] = 'FLWW'
  version u32          # FNV-1a of paths+sizes+bytes
  file_count u32
  total_bytes u32      # sum of file payloads (for progress)
  repeated:
    path_len u16
    path[path_len]     # relative, '/' separators, no leading slash
    size u32
    data[size]
"""
from __future__ import annotations

import os
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WWW = ROOT / "build" / "temp" / "www"
OUT_PAK = ROOT / "build" / "temp" / "www.pak"
OUT_META = ROOT / "src" / "net" / "www_bundle_meta.h"


def fnv1a32(data: bytes, h: int = 0x811C9DC5) -> int:
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def collect_files(www: Path) -> list[tuple[str, Path]]:
    files: list[tuple[str, Path]] = []
    # Case-sensitive order by path parts: same bundle (and version) on macOS, Linux and Windows.
    for p in sorted(www.rglob("*"), key=lambda q: q.relative_to(www).parts):
        if not p.is_file():
            continue
        if p.name == ".DS_Store":
            continue
        rel = p.relative_to(www).as_posix()
        if ".." in rel.split("/"):
            raise SystemExit(f"bad path: {rel}")
        files.append((rel, p))
    if not files:
        raise SystemExit(f"no files under {www}")
    if not any(r == "index.html" for r, _ in files):
        raise SystemExit("build/temp/www/index.html missing — run: cd web && npm run build")
    return files


def main() -> int:
    if not WWW.is_dir():
        print(f"missing {WWW}", file=sys.stderr)
        return 1

    files = collect_files(WWW)
    version = 0x811C9DC5
    blobs: list[tuple[str, bytes]] = []
    total = 0
    for rel, path in files:
        data = path.read_bytes()
        version = fnv1a32(rel.encode("ascii"), version)
        version = fnv1a32(struct.pack("<I", len(data)), version)
        version = fnv1a32(data, version)
        blobs.append((rel, data))
        total += len(data)

    OUT_PAK.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PAK.open("wb") as f:
        f.write(b"FLWW")
        f.write(struct.pack("<III", version, len(blobs), total))
        for rel, data in blobs:
            pb = rel.encode("ascii")
            if len(pb) > 65535:
                raise SystemExit(f"path too long: {rel}")
            f.write(struct.pack("<H", len(pb)))
            f.write(pb)
            f.write(struct.pack("<I", len(data)))
            f.write(data)

    OUT_META.write_text(
        "/* Auto-generated by scripts/pack_www.py — do not edit. */\n"
        f"#ifndef FLSUN_WWW_BUNDLE_META_H\n"
        f"#define FLSUN_WWW_BUNDLE_META_H\n\n"
        f"#define WWW_BUNDLE_VERSION 0x{version:08X}u\n"
        f"#define WWW_BUNDLE_FILES   {len(blobs)}\n"
        f"#define WWW_BUNDLE_BYTES   {total}\n"
        f"#define WWW_PAK_NAME       \"www.pak\"\n\n"
        f"#endif\n",
        encoding="utf-8",
        newline="\n",
    )

    pak_sz = OUT_PAK.stat().st_size
    print(
        f"packed {len(blobs)} files, {total} bytes payload, "
        f"pak {pak_sz} bytes, ver 0x{version:08X}"
    )
    print(f"→ {OUT_PAK}")
    print(f"→ {OUT_META}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
